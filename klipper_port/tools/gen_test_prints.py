#!/usr/bin/env python3
"""Generate simple first test prints for the DP200 (no slicer needed).

  dp200_first_layer.gcode  one 0.25 mm layer: 50x50 mm square, 3 perimeters
                           + 45-degree infill, centred on the bed
  dp200_box_20mm.gcode     20x20x10 mm open box: 2 perimeters, 3 solid
                           bottom layers, no top

Both start with PRINT_START (heat, home, bed mesh, purge/wipe) and end with
PRINT_END, use relative E (M83) and label the object for [exclude_object].
Usage: gen_test_prints.py OUTDIR [--bed 60] [--extruder 210]
"""
import argparse
import math
import os

FIL_AREA = math.pi * (1.75 / 2) ** 2
CX, CY = 100.0, 100.0          # bed centre (200 x 200 mm bed)


def e_per_mm(width, height):
    # slicer flow model: rectangle with semicircular ends
    return ((width - height) * height + math.pi * (height / 2) ** 2) / FIL_AREA


class G:
    def __init__(self, name, bed, ext, retract=4.0, retract_speed=35):
        self.lines = []
        self.x = self.y = None
        self.retracted = False
        self.retract = retract
        self.rs = retract_speed * 60
        self.name = name
        self.bed, self.ext = bed, ext

    def emit(self, s):
        self.lines.append(s)

    def travel(self, x, y, speed=100):
        if self.x is not None and math.hypot(x - self.x, y - self.y) > 2 and not self.retracted:
            self.emit('G1 E-%.2f F%d' % (self.retract, self.rs))
            self.retracted = True
        self.emit('G0 X%.3f Y%.3f F%d' % (x, y, speed * 60))
        self.x, self.y = x, y

    def extrude(self, x, y, epm, speed):
        if self.retracted:
            self.emit('G1 E%.2f F%d' % (self.retract, self.rs))
            self.retracted = False
        d = math.hypot(x - self.x, y - self.y)
        self.emit('G1 X%.3f Y%.3f E%.5f F%d' % (x, y, d * epm, speed * 60))
        self.x, self.y = x, y

    def rect(self, x0, y0, x1, y1, epm, speed):
        self.travel(x0, y0)
        for x, y in ((x1, y0), (x1, y1), (x0, y1), (x0, y0)):
            self.extrude(x, y, epm, speed)

    def infill(self, x0, y0, x1, y1, spacing, epm, speed, angle45=True, flip=False):
        """Lines at +-45 degrees clipped to the rectangle (zig-zag)."""
        w, h = x1 - x0, y1 - y0
        n = int((w + h) / (spacing * math.sqrt(2)))
        segs = []
        for i in range(1, n):
            c = i * spacing * math.sqrt(2)          # x + y = c (or x - y)
            pts = []
            # intersections of x+y=c with the box (local coords)
            for (px, py) in ((c, 0), (0, c), (c - h, h), (w, c - w)):
                if -1e-9 <= px <= w + 1e-9 and -1e-9 <= py <= h + 1e-9:
                    pts.append((px, py))
            pts = sorted(set((round(px, 6), round(py, 6)) for px, py in pts))
            if len(pts) < 2:
                continue
            a, b = pts[0], pts[-1]
            if flip:
                a, b = (w - a[0], a[1]), (w - b[0], b[1])
            if i % 2:
                a, b = b, a
            segs.append(((x0 + a[0], y0 + a[1]), (x0 + b[0], y0 + b[1])))
        for (ax, ay), (bx, by) in segs:
            if self.x is not None and math.hypot(ax - self.x, ay - self.y) < 2 * spacing:
                self.extrude(ax, ay, epm, speed)    # short connector, no retract
            else:
                self.travel(ax, ay)
            self.extrude(bx, by, epm, speed)

    def header(self, size_x, size_y):
        x0, x1 = CX - size_x / 2, CX + size_x / 2
        y0, y1 = CY - size_y / 2, CY + size_y / 2
        self.emit('; generated by klipper_port/tools/gen_test_prints.py')
        self.emit('; %s - PLA, bed %d C, nozzle %d C' % (self.name, self.bed, self.ext))
        self.emit('EXCLUDE_OBJECT_DEFINE NAME=%s CENTER=%.1f,%.1f POLYGON=[[%.1f,%.1f],[%.1f,%.1f],[%.1f,%.1f],[%.1f,%.1f]]'
                  % (self.name, CX, CY, x0, y0, x1, y0, x1, y1, x0, y1))
        self.emit('PRINT_START BED=%d EXTRUDER=%d' % (self.bed, self.ext))
        self.emit('G90')
        self.emit('M83')
        self.emit('M106 S0')
        # PRINT_START ends over the bed centre at Z 10: travel at Z 5, then down,
        # then a prime line in front of the object (inside the mesh area)
        py = y0 - 8
        self.emit('G0 Z5 F600')
        self.travel(CX - 35, py)
        self.emit('G0 Z0.300 F600')
        self.extrude(CX + 35, py, e_per_mm(0.6, 0.3), 15)
        self.extrude(CX + 35, py + 0.6, e_per_mm(0.6, 0.3), 15)
        self.extrude(CX - 5, py + 0.6, e_per_mm(0.6, 0.3), 15)
        self.emit('EXCLUDE_OBJECT_START NAME=%s' % self.name)

    def layer(self, z, n):
        self.emit(';LAYER:%d' % n)
        self.emit('G0 Z%.3f F600' % z)

    def footer(self):
        self.emit('EXCLUDE_OBJECT_END NAME=%s' % self.name)
        self.emit('PRINT_END')

    def save(self, path):
        with open(path, 'w', newline='\n') as f:
            f.write('\n'.join(self.lines) + '\n')


def first_layer(bed, ext):
    g = G('first_layer_50mm', bed, ext)
    g.header(50, 50)
    h, w = 0.25, 0.45
    epm = e_per_mm(w, h)
    g.layer(h, 0)
    half = 25.0
    for i in range(3):
        o = half - w / 2 - i * w
        g.rect(CX - o, CY - o, CX + o, CY + o, epm, 20)
    o = half - 3 * w
    g.infill(CX - o, CY - o, CX + o, CY + o, w, epm, 25)
    g.footer()
    return g


def box(bed, ext):
    g = G('box_20mm', bed, ext)
    g.header(20, 20)
    w = 0.45
    z, n = 0.0, 0
    while z < 10.0 - 1e-6:
        h = 0.25 if n == 0 else 0.2
        z += h
        epm = e_per_mm(w, h)
        g.layer(z, n)
        if n == 2:
            g.emit('M106 S255')                     # part fan from layer 3 (PLA)
        speed = 20 if n == 0 else 30
        half = 10.0
        for i in range(2):
            o = half - w / 2 - i * w
            g.rect(CX - o, CY - o, CX + o, CY + o, epm, speed)
        if n < 3:
            o = half - 2 * w
            g.infill(CX - o, CY - o, CX + o, CY + o, w, epm, speed, flip=bool(n % 2))
        n += 1
    g.footer()
    return g


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('outdir')
    ap.add_argument('--bed', type=int, default=60)
    ap.add_argument('--extruder', type=int, default=210)
    a = ap.parse_args()
    os.makedirs(a.outdir, exist_ok=True)
    for fn, g in (('dp200_first_layer.gcode', first_layer(a.bed, a.extruder)),
                  ('dp200_box_20mm.gcode', box(a.bed, a.extruder))):
        p = os.path.join(a.outdir, fn)
        g.save(p)
        e = sum(float(l.split('E')[1].split()[0]) for l in g.lines
                if l.startswith('G1 X') and ' E' in l)
        print('%s: %d lines, %.0f mm filament' % (p, len(g.lines), e))


if __name__ == '__main__':
    main()
