"""Generate Klipper [adc_temperature] tables from the stock Sindoh lookup tables.
usage: gen_thermistors.py marvell_lspsdk_3dp_gemstone-debug_stripped.elf
Stock: table entry i = m°C for 11-bit code (base + i); code = raw*2048/1023,
so Klipper voltage (raw/1023 with adc_voltage 1) = code/2048."""
import struct, sys
from elftools.elf.elffile import ELFFile

e = ELFFile(open(sys.argv[1], 'rb'))
syms = {s.name: s for s in e.get_section_by_name('.dynsym').iter_symbols()}
segs = [(s['p_vaddr'], s.data()) for s in e.iter_segments() if s['p_type'] == 'PT_LOAD']

def read(name, size):
    a = syms[name]['st_value']
    for va, d in segs:
        if va <= a < va + len(d):
            return d[a - va:a - va + size]
    raise SystemExit('%s not in a loaded segment' % name)

def table(name, size, base, title, tmin, tmax, step):
    vals = struct.unpack('<%di' % (size // 4), read(name, size))
    pts = []
    target = tmin
    for i, mc in sorted(enumerate(vals), key=lambda x: x[1]):     # ascending temperature
        t = mc / 1000.0
        if t >= target and t <= tmax:
            pts.append((t, (base + i) / 2048.0))
            target = (int(t) // step + 1) * step
    out = ['[adc_temperature %s]' % title,
           '# generated by tools/gen_thermistors.py from %s (stock firmware table)' % name]
    for n, (t, v) in enumerate(pts, 1):
        out.append('temperature%d: %.1f' % (n, t))
        out.append('voltage%d: %.5f' % (n, v))
    return '\n'.join(out) + '\n'

print(table('adc_temp_mC_lookup_table', 0x1e48, 0x6e, 'dp200_nozzle', 0, 300, 10))
print(table('adc_bed_mC_lookup_table', 0x1a0c, 0x17d, 'dp200_bed', 0, 130, 10))
